def quotient_is_z3(group: list, v4: list, tol: float = 1e-6) -> dict:
    """A4/V4 has order 3 and is cyclic (the three generations)."""

    def in_v4(M):
        return any(np.allclose(M, h, atol=tol) for h in v4)

    # Cosets g V4.
    cosets = []
    for g in group:
        rep_set = [g @ h for h in v4]
        # Identify by a canonical key of the sorted coset.
        is_new = True
        for c in cosets:
            if any(np.allclose(g, x, atol=tol) for x in c):
                is_new = False
                break
        if is_new:
            cosets.append(rep_set)
    order = len(cosets)
    # Normality: g V4 g^-1 = V4 for all g.
    normal = all(in_v4(g @ h @ g.T) for g in group for h in v4)
    return {"quotient_order": order, "normal": normal, "is_Z3": order == 3 and normal}


