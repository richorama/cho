def burnside_span_dimension(elems: list) -> int:
    """Complex dim of the linear span of a set of 2x2 matrices (M2(C) = 4)."""
    vs = np.array([E.ravel() for E in elems])  # rows = vec(E), complex
    # Rank over C via SVD of the complex matrix.
    s = np.linalg.svd(vs, compute_uv=False)
    return int(np.sum(s > 1e-9))


def commutant_dimension(elems: list) -> int:
    """Complex dim of {X : X E = E X for all E} -- 1 iff irreducible (Schur)."""
    rows = []
    for E in elems:
        # vec(E X - X E) = (I (x) E - E^T (x) I) vec(X) = 0.
        rows.append(np.kron(np.eye(2), E) - np.kron(E.T, np.eye(2)))
    A = np.vstack(rows)
    s = np.linalg.svd(A, compute_uv=False)
    rank = int(np.sum(s > 1e-9))
    return 4 - rank


def su2_lie_algebra_dimension(elems: list) -> int:
    """Real dim of the span of the traceless anti-Hermitian parts (su(2) = 3)."""
    gens = []
    for E in elems:
        A = E - E.conj().T              # anti-Hermitian part
        A = A - np.trace(A) / 2.0 * np.eye(2)  # traceless
        if np.linalg.norm(A) > 1e-9:
            gens.append(A.ravel())
    if not gens:
        return 0
    # Real dimension: stack real and imaginary parts.
    M = np.array(gens)
    real_rows = np.vstack([M.real, M.imag])
    s = np.linalg.svd(real_rows, compute_uv=False)
    return int(np.sum(s > 1e-9))


