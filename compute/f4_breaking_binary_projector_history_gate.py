def f4_binary_transport_witness(n_auto: int = 8, seed: int = 20260610) -> F4BinaryTransportWitness:
    _psi, _phi, source_projector, event_projector = transition_projectors(EPS0)
    identity = identity_idempotent()
    base_yes_probability = trace_form(source_projector, event_projector)
    rng = np.random.default_rng(seed)
    f4 = _f4_basis()
    max_yes_probability_error = 0.0
    max_probability_sum_error = 0.0
    max_idempotent_error = 0.0
    max_orthogonality_error = 0.0
    max_rank_error = 0.0
    min_octonionic = math.inf
    for _ in range(n_auto):
        automorphism = random_automorphism(rng, f4, 0.9)
        transported_source = automorphism @ source_projector
        transported_event = automorphism @ event_projector
        transported_complement = identity - transported_event
        yes_probability = trace_form(transported_source, transported_event)
        no_probability = trace_form(transported_source, transported_complement)
        max_yes_probability_error = max(max_yes_probability_error, abs(yes_probability - base_yes_probability))
        max_probability_sum_error = max(max_probability_sum_error, abs(yes_probability + no_probability - 1.0))
        for effect in (transported_event, transported_complement):
            max_idempotent_error = max(
                max_idempotent_error,
                float(np.linalg.norm(jordan_product(effect, effect) - effect)),
            )
        max_orthogonality_error = max(
            max_orthogonality_error,
            float(np.linalg.norm(jordan_product(transported_event, transported_complement))),
        )
        for projector in (transported_source, transported_event):
            max_rank_error = max(max_rank_error, abs(cubic_norm(projector)))
        min_octonionic = min(
            min_octonionic,
            max(octonionic_support(transported_source), octonionic_support(transported_event)),
        )
    return F4BinaryTransportWitness(
        base_yes_probability=float(base_yes_probability),
        max_yes_probability_error=float(max_yes_probability_error),
        max_probability_sum_error=float(max_probability_sum_error),
        max_idempotent_error=float(max_idempotent_error),
        max_orthogonality_error=float(max_orthogonality_error),
        max_rank_error=float(max_rank_error),
        min_octonionic_support=float(min_octonionic),
    )


def _binomial_coefficient(total_trials: int, successes: int) -> int:
    return math.factorial(total_trials) // (math.factorial(successes) * math.factorial(total_trials - successes))


def binary_history_counting_rows() -> tuple[BinaryHistoryCountingRow, ...]:
    probability = EPS0_SQ
    rows = []
    for total_trials in (4, 8, 12):
        history_count = 2 ** total_trials
        binomial_count_sum = sum(_binomial_coefficient(total_trials, successes) for successes in range(total_trials + 1))
        probability_sum = 0.0
        mean_successes = 0.0
        mean_successes_squared = 0.0
        for successes in range(total_trials + 1):
            multiplicity = _binomial_coefficient(total_trials, successes)
            probability_mass = multiplicity * (probability ** successes) * ((1.0 - probability) ** (total_trials - successes))
            probability_sum += probability_mass
            mean_successes += successes * probability_mass
            mean_successes_squared += (successes * successes) * probability_mass
        mean_density = mean_successes / total_trials
        variance_successes = mean_successes_squared - mean_successes * mean_successes
        variance_density = variance_successes / (total_trials * total_trials)
        binomial_variance_density = probability * (1.0 - probability) / total_trials
        rows.append(
            BinaryHistoryCountingRow(
                total_trials=int(total_trials),
                history_count=int(history_count),
                binomial_count_sum=int(binomial_count_sum),
                count_sum_error=int(abs(binomial_count_sum - history_count)),
                probability_sum=float(probability_sum),
                probability_sum_error=abs(probability_sum - 1.0),
                mean_success_density=float(mean_density),
                mean_error=abs(mean_density - probability),
                variance_density=float(variance_density),
                binomial_variance_density=float(binomial_variance_density),
                variance_error=abs(variance_density - binomial_variance_density),
            )
        )
    return tuple(rows)


