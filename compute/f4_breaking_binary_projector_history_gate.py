def identity_idempotent() -> np.ndarray:
    frame = primitive_idempotents()
    return frame[0] + frame[1] + frame[2]


def projector_complement(projector: np.ndarray) -> np.ndarray:
    return identity_idempotent() - projector


def binary_projector_row(label: str, amplitude: float, interpretation: str) -> BinaryProjectorRow:
    if not 0.0 < amplitude < 1.0:
        raise ValueError("amplitude must lie in (0, 1)")
    _psi, _phi, source_projector, event_projector = transition_projectors(amplitude)
    complement = projector_complement(event_projector)
    yes_probability = trace_form(source_projector, event_projector)
    no_probability = trace_form(source_projector, complement)
    yes_idempotent_error = float(np.linalg.norm(jordan_product(event_projector, event_projector) - event_projector))
    no_idempotent_error = float(np.linalg.norm(jordan_product(complement, complement) - complement))
    orthogonality_error = float(np.linalg.norm(jordan_product(event_projector, complement)))
    target_error = abs(yes_probability - EPS0_SQ)
    binary_projector_event = (
        yes_idempotent_error < TOL
        and no_idempotent_error < TOL
        and orthogonality_error < TOL
        and abs(yes_probability + no_probability - 1.0) < TOL
    )
    return BinaryProjectorRow(
        label=label,
        amplitude=float(amplitude),
        yes_probability=float(yes_probability),
        no_probability=float(no_probability),
        probability_sum_error=abs(yes_probability + no_probability - 1.0),
        yes_idempotent_error=yes_idempotent_error,
        no_idempotent_error=no_idempotent_error,
        orthogonality_error=orthogonality_error,
        target_error=float(target_error),
        binary_projector_event=bool(binary_projector_event),
        matches_target=target_error < MATCH_TOL,
        interpretation=interpretation,
    )


def scaled_effect_row(scale: float = 1.0 / 432.0) -> BinaryProjectorRow:
    _psi, _phi, source_projector, _event_projector = transition_projectors(EPS0)
    effect = scale * identity_idempotent()
    complement = identity_idempotent() - effect
    yes_probability = trace_form(source_projector, effect)
    no_probability = trace_form(source_projector, complement)
    yes_idempotent_error = float(np.linalg.norm(jordan_product(effect, effect) - effect))
    no_idempotent_error = float(np.linalg.norm(jordan_product(complement, complement) - complement))
    orthogonality_error = float(np.linalg.norm(jordan_product(effect, complement)))
    target_error = abs(yes_probability - EPS0_SQ)
    return BinaryProjectorRow(
        label="state-count scaled effect",
        amplitude=float(math.sqrt(scale)),
        yes_probability=float(yes_probability),
        no_probability=float(no_probability),
        probability_sum_error=abs(yes_probability + no_probability - 1.0),
        yes_idempotent_error=yes_idempotent_error,
        no_idempotent_error=no_idempotent_error,
        orthogonality_error=orthogonality_error,
        target_error=float(target_error),
        binary_projector_event=False,
        matches_target=False,
        interpretation="wrong: normalized effect is not an idempotent projective yes/no question and omits Berry pi",
    )


